#ifndef LMUX_HOST_CONTROL_STRUCTURED_H
#define LMUX_HOST_CONTROL_STRUCTURED_H

#include <stdint.h>
#include <stddef.h>

#define LMUX_HC2_MAGIC 0x3243484cU /* "LHC2" little-endian */
#define LMUX_HC2_VERSION 1
#define LMUX_HC2_HEADER_LEN 24
#define LMUX_HC2_MAX_PAYLOAD 4096
#define LMUX_HC2_TX_CAP 65536
#define LMUX_HC2_RX_CAP (LMUX_HC2_HEADER_LEN + LMUX_HC2_MAX_PAYLOAD)
#define LMUX_HC2_MAX_ARGC 16
#define LMUX_HC2_MAX_ARG_BYTES 4096

enum lmux_hc2_type {
    LMUX_HC2_CLIENT_HELLO = 1,
    LMUX_HC2_SERVER_HELLO = 2,
    LMUX_HC2_ERROR = 3,

    LMUX_HC2_STATUS_REQUEST = 10,
    LMUX_HC2_STATUS_REPLY = 11,

    LMUX_HC2_EXEC_START = 20,
    LMUX_HC2_EXEC_STARTED = 21,
    LMUX_HC2_EXEC_ATTACH = 22,
    LMUX_HC2_EXEC_STATUS = 23,
    LMUX_HC2_EXEC_STDIN_DATA = 24,
    LMUX_HC2_EXEC_STDIN_CLOSE = 25,
    LMUX_HC2_EXEC_SIGNAL = 26,
    LMUX_HC2_EXEC_RELEASE = 27,

    LMUX_HC2_EXEC_STDOUT = 40,
    LMUX_HC2_EXEC_STDERR = 41,
    LMUX_HC2_EXEC_STATE = 42,
    LMUX_HC2_EXEC_LOST = 43,
    LMUX_HC2_EXEC_STDIN_READY = 44,

    LMUX_HC2_FILE_PUT_START = 60,
    LMUX_HC2_FILE_GET_START = 61,
    LMUX_HC2_FILE_STARTED = 62,
    LMUX_HC2_FILE_PROGRESS = 65,
    LMUX_HC2_FILE_DONE = 63,
    LMUX_HC2_FILE_ERROR = 64
};

enum lmux_hc2_error {
    LMUX_HC2_OK = 0,
    LMUX_HC2_E_INVALID_ARGUMENT = 1,
    LMUX_HC2_E_NOT_CONNECTED = 2,
    LMUX_HC2_E_SERVICE_UNAVAILABLE = 3,
    LMUX_HC2_E_NOT_FOUND = 4,
    LMUX_HC2_E_STALE_TARGET = 5,
    LMUX_HC2_E_BUSY = 6,
    LMUX_HC2_E_RESOURCE_LIMIT = 7,
    LMUX_HC2_E_TARGET_LOST = 8,
    LMUX_HC2_E_IO = 9,
    LMUX_HC2_E_PROTOCOL = 10,
    LMUX_HC2_E_INTERNAL = 11
};

enum lmux_hc2_caps {
    LMUX_HC2_CAP_STATUS = 1u << 0,
    LMUX_HC2_CAP_EXEC = 1u << 1,
    LMUX_HC2_CAP_FILE = 1u << 2
};

enum lmux_hc2_exec_signal {
    LMUX_HC2_SIG_INT = 1,
    LMUX_HC2_SIG_TERM = 2,
    LMUX_HC2_SIG_KILL = 3,
    LMUX_HC2_SIG_HUP = 4
};

void lmux_hc2_put_u64(uint8_t *p, uint64_t v);
uint64_t lmux_hc2_get_u64(const uint8_t *p);

#endif
